create function private.medicine_command(request_id uuid,command_type text,payload jsonb) returns jsonb language plpgsql security definer set search_path='' as $$
declare actor uuid:=auth.uid(); prior private.medicine_receipts; profile public.medicine_profiles; current_revision integer; row_id uuid; response jsonb; unit private.medicine_units; academic text; target_year integer; allowed text[];
begin
 if not coalesce(private.classroom_can_study(actor),false) or not coalesce(private.education_can_draft(actor),false) then raise exception 'STUDENT_REQUIRED';end if;
 if request_id is null or jsonb_typeof(payload) is distinct from 'object' or jsonb_typeof(payload->'expected_revision') is distinct from 'number' or (payload->>'expected_revision')::numeric<0 or (payload->>'expected_revision')::numeric<>trunc((payload->>'expected_revision')::numeric) then raise exception 'INVALID_INPUT';end if;
 perform pg_advisory_xact_lock(hashtextextended('medicine:'||actor::text,0));
 select * into prior from private.medicine_receipts r where r.user_id=actor and r.request_id=medicine_command.request_id;
 if found then
  if prior.command_type<>command_type or prior.payload<>payload then raise exception 'IDEMPOTENCY_CONFLICT';end if;
  return prior.result||jsonb_build_object('replayed',true);
 end if;
 select * into profile from public.medicine_profiles p where p.user_id=actor;
 if command_type='profile.save' then
  allowed:=array['academic_year','active_year','enabled','expected_revision'];
 elsif command_type='topic.save' then
  allowed:=array['academic_year','topic_id','mastery','review_requested','notes','expected_revision'];
 elsif command_type='result.save' then
  allowed:=array['academic_year','year','unit_id','attempt','exam_date','reported_score','theory_score','practical_score','notes','expected_revision'];
 elsif command_type='result.delete' then
  allowed:=array['id','expected_revision'];
 elsif command_type='keg.save' then
  allowed:=array['academic_year','year','status','assessment_date','notes','expected_revision'];
 else raise exception 'INVALID_INPUT';end if;
 if exists(select 1 from jsonb_object_keys(payload) k where not k=any(allowed)) then raise exception 'INVALID_INPUT';end if;
 if command_type='profile.save' then
  if not exists(select 1 from public.education_profiles p where p.user_id=actor and p.education_level='university') then raise exception 'INVALID_INPUT';end if;
  if coalesce(profile.revision,0)<>(payload->>'expected_revision')::integer then raise exception 'CONFLICT';end if;
  if jsonb_typeof(payload->'enabled')<>'boolean' then raise exception 'INVALID_INPUT';end if;
  insert into public.medicine_profiles(user_id,academic_year,active_year,enabled) values(actor,payload->>'academic_year',(payload->>'active_year')::integer,(payload->>'enabled')::boolean)
  on conflict(user_id) do update set academic_year=excluded.academic_year,active_year=excluded.active_year,enabled=excluded.enabled,revision=medicine_profiles.revision+1,updated_at=now();
  row_id:=actor;
