create table public.medicine_profiles(
 user_id uuid primary key references auth.users(id) on delete cascade,
 academic_year text not null check(academic_year ~ '^20[0-9]{2}-20[0-9]{2}$' and right(academic_year,4)::integer=left(academic_year,4)::integer+1),
 active_year integer not null check(active_year between 1 and 4),
 enabled boolean not null default true,catalog_version text not null default 'klu-2026-2027' check(catalog_version='klu-2026-2027'),
 revision integer not null default 1,updated_at timestamptz not null default now());
create table public.medicine_topic_progress(
 user_id uuid not null references auth.users(id) on delete cascade,academic_year text not null,
 topic_id text not null references private.medicine_topics(id),mastery integer not null check(mastery between 0 and 4),
 review_requested boolean not null default false,notes text not null default '' check(length(notes)<=10000),revision integer not null default 1,updated_at timestamptz not null default now(),
 primary key(user_id,academic_year,topic_id));
create table public.medicine_results(
 id uuid primary key default gen_random_uuid(),user_id uuid not null references auth.users(id) on delete cascade,
 academic_year text not null,year integer not null check(year between 1 and 4),unit_id text not null references private.medicine_units(id),
 attempt text not null check(attempt in ('regular','resit')),exam_date date not null,
 reported_score numeric check(reported_score between 0 and 100),theory_score numeric check(theory_score between 0 and 100),practical_score numeric check(practical_score between 0 and 100),
 notes text not null default '' check(length(notes)<=2000),revision integer not null default 1,updated_at timestamptz not null default now(),
 check((reported_score is not null and theory_score is null and practical_score is null) or (reported_score is null and (theory_score is not null or practical_score is not null))),
 unique(user_id,academic_year,unit_id,attempt));
create table public.medicine_keg(
 user_id uuid not null references auth.users(id) on delete cascade,academic_year text not null,year integer not null check(year between 1 and 3),
 status text not null check(status in ('not_recorded','sufficient','insufficient')),assessment_date date,
 notes text not null default '' check(length(notes)<=2000),revision integer not null default 1,updated_at timestamptz not null default now(),primary key(user_id,academic_year,year));
create table private.medicine_receipts(user_id uuid not null references auth.users(id) on delete cascade,request_id uuid not null,command_type text not null,payload jsonb not null,result jsonb not null,created_at timestamptz not null default now(),primary key(user_id,request_id));
revoke all on private.medicine_receipts from public,anon,authenticated,service_role;
do $$ declare t text;begin
