 end loop;
end $$;

create function private.medicine_state_for(actor uuid) returns jsonb language sql stable security definer set search_path='' as $$
 select jsonb_build_object(
 'profile',(select to_jsonb(p)-'user_id'-'updated_at' from public.medicine_profiles p where p.user_id=actor),
 'progress',coalesce((select jsonb_agg(to_jsonb(t)-'user_id'-'updated_at' order by t.topic_id) from public.medicine_topic_progress t join public.medicine_profiles p on p.user_id=t.user_id join private.medicine_topics c on c.id=t.topic_id where t.user_id=actor and t.academic_year=p.academic_year and c.year=p.active_year),'[]'),
 'results',coalesce((select jsonb_agg(to_jsonb(r)-'user_id' order by unit_id,attempt) from public.medicine_results r join public.medicine_profiles p on p.user_id=r.user_id where r.user_id=actor and r.academic_year=p.academic_year and r.year=p.active_year),'[]'),
 'keg',coalesce((select jsonb_agg(to_jsonb(k)-'user_id'-'updated_at') from public.medicine_keg k join public.medicine_profiles p on p.user_id=k.user_id where k.user_id=actor and k.academic_year=p.academic_year and k.year=p.active_year),'[]'))
$$;
